/**
 * 渲染每员工的装配文件：基座 assets/agent.cordis.yml（rc.6/rc.8 实测通过的最小装配）
 * + 员工人设（system-prompt.persona）+ 会话持久化根。
 *
 * 纪律（CLAUDE.md 边界 2/5）：渲染器**只改基座已有条目的 config，不新增插件条目**；
 * 不得挂 stdout logger；jsonrpc 条目必须保留。任何违反都在渲染期抛错而不是上线后翻车。
 */
import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, stat, symlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parse as parseYaml, stringify as toYaml } from 'yaml';
import type { AgentRecord, AgentStore } from '../store/agent-store.js';

export interface CordisEntry {
  id: string;
  name: string;
  config?: Record<string, unknown>;
}

/** 装配作用域：租户/账号（已经 assertPathSegment 校验的安全段）；带 session 时每会话一份（会话技能目录不同） */
export interface AssemblyScope {
  tenant: string;
  user: string;
  session?: string;
  /** 额外技能根（会话技能目录），与员工静态 skills 目录一起进 customSkillDirs */
  extraSkillDirs?: string[];
  /** 额外插入的装配条目（如每会话的 mcp-client 工具桥），插在 system-prompt 之前 */
  extraEntries?: CordisEntry[];
  /** 追加到人设后的系统提示片段（平台工具使用纪律等） */
  personaSuffix?: string;
}

export interface RenderInputs {
  baseYaml: string;
  agent: Pick<AgentRecord, 'agent_key' | 'system_prompt' | 'revision' | 'tools'>;
  /** 会话 jsonl 落点（绝对路径） */
  sessionsRoot: string;
  /** 平台内置技能根（assets/skills，从 OpenClaw 平移，所有员工共享，只读） */
  platformSkillsDir?: string;
  /** 员工静态 skills 目录 + 会话技能目录；基座若无 skill-filesystem 条目则忽略 */
  skillsDir?: string;
  extraSkillDirs?: string[];
  extraEntries?: CordisEntry[];
  personaSuffix?: string;
  /** 部署级默认关闭的逻辑工具（员工未显式 allow 时生效）；见 assemble/tool-gate.ts */
  toolDefaultDeny?: readonly LogicalTool[];
}

import { disabledPluginIds, type LogicalTool } from './tool-gate.js';

const FORBIDDEN_NAME_RE = /logger|stdout/i;

export function parseBase(baseYaml: string): CordisEntry[] {
  const parsed = parseYaml(baseYaml) as unknown;
  if (!Array.isArray(parsed)) throw new Error('base assembly must be a YAML list of plugin entries');
  return parsed.map((e, i) => {
    if (typeof e !== 'object' || e === null || typeof (e as CordisEntry).id !== 'string' || typeof (e as CordisEntry).name !== 'string') {
      throw new Error(`base assembly entry #${i} must have string id and name`);
    }
    return e as CordisEntry;
  });
}

export function renderCordis(inputs: RenderInputs): string {
  const entries = parseBase(inputs.baseYaml).map((e) => ({ ...e, config: e.config ? { ...e.config } : undefined }));
  const byId = new Map(entries.map((e) => [e.id, e]));

  const persona = byId.get('system-prompt');
  if (!persona) throw new Error('base assembly lacks system-prompt entry');
  persona.config = { ...(persona.config ?? {}), persona: inputs.personaSuffix ? `${inputs.agent.system_prompt}\n\n${inputs.personaSuffix}` : inputs.agent.system_prompt };
  if (inputs.extraEntries && inputs.extraEntries.length > 0) {
    const at = entries.findIndex((e) => e.id === 'system-prompt');
    for (const extra of inputs.extraEntries) {
      if (byId.has(extra.id)) throw new Error(`extra assembly entry id collides: ${extra.id}`);
    }
    entries.splice(at, 0, ...inputs.extraEntries.map((e) => ({ ...e, config: e.config ? { ...e.config } : undefined })));
  }

  const persistence = byId.get('session-persistence-jsonl');
  if (!persistence) throw new Error('base assembly lacks session-persistence-jsonl entry');
  persistence.config = { ...(persistence.config ?? {}), root: resolve(inputs.sessionsRoot) };

  const skills = byId.get('skill-filesystem');
  if (skills && (inputs.platformSkillsDir || inputs.skillsDir || inputs.extraSkillDirs?.length)) {
    const dirs = [...(inputs.platformSkillsDir ? [inputs.platformSkillsDir] : []), ...(inputs.skillsDir ? [inputs.skillsDir] : []), ...(inputs.extraSkillDirs ?? [])].map((d) => resolve(d));
    skills.config = { ...(skills.config ?? {}), customSkillDirs: [...new Set(dirs)] };
  }

  if (!byId.has('jsonrpc')) throw new Error('base assembly lacks jsonrpc entry');
  for (const e of entries) {
    if (FORBIDDEN_NAME_RE.test(e.name) || FORBIDDEN_NAME_RE.test(e.id)) {
      throw new Error(`assembly must not load a stdout logger (${e.name})`);
    }
  }

  // 按员工的 tools.allow/deny 剔除工具插件（admin 配了但此前不生效, 见 assemble/tool-gate.ts）。
  // 放在最后统一过滤: extraEntries 注入的平台工具桥同样受管。
  const disabled = disabledPluginIds(inputs.agent.tools, inputs.toolDefaultDeny ?? []);
  const kept = disabled.size === 0 ? entries : entries.filter((e) => !disabled.has(e.id));

  const header = `# generated by dsh-runtime assemble for agent ${inputs.agent.agent_key} (revision ${inputs.agent.revision}) — do not edit\n`;
  return header + toYaml(kept.map((e) => (e.config === undefined ? { id: e.id, name: e.name } : e)));
}

/**
 * per-agent 装配文件缓存：<cordisDir>/<agent_key>/cordis.yml，内容随 revision 变化重渲染。
 * 另在 <cordisDir>/node_modules 补软链 → 包 node_modules，保证裸包名可解析。
 */
export class CordisCache {
  private readonly rendered = new Map<string, number>();
  private readonly renderedSkillDirs = new Map<string, string>();
  private readonly inflight = new Map<string, Promise<string>>();
  private baseYaml: string | undefined;

  constructor(
    private readonly opts: {
      baseCordisPath: string;
      cordisDir: string;
      sessionsRoot: string;
      packageNodeModules: string;
      platformSkillsDir?: string;
      /** 部署级默认关闭的逻辑工具；见 assemble/tool-gate.ts */
      toolDefaultDeny?: readonly LogicalTool[];
    },
    private readonly store: AgentStore,
  ) {
    store.onChange((key) => this.rendered.delete(key));
  }

  async init(): Promise<void> {
    await mkdir(this.opts.cordisDir, { recursive: true });
    await mkdir(this.opts.sessionsRoot, { recursive: true });
    this.baseYaml = await readFile(this.opts.baseCordisPath, 'utf8');
    const link = join(this.opts.cordisDir, 'node_modules');
    try {
      await stat(link);
    } catch {
      await symlink(this.opts.packageNodeModules, link, 'dir');
    }
  }

  /**
   * 装配文件路径。带 scope（租户/账号）时按 `<cordisDir>/<agent_key>/<tenant>/<user>/cordis.yml` 分目录：
   * 会话持久化根随之落到 `<sessionsRoot>/<tenant>/<user>`，读隔离只需授权这一对目录，
   * 其它租户的会话日志与装配（含人设）对本进程不可读。
   */
  pathFor(agentKey: string, scope?: AssemblyScope): string {
    if (!scope) return join(this.opts.cordisDir, agentKey, 'cordis.yml');
    return scope.session
      ? join(this.opts.cordisDir, agentKey, scope.tenant, scope.user, scope.session, 'cordis.yml')
      : join(this.opts.cordisDir, agentKey, scope.tenant, scope.user, 'cordis.yml');
  }

  /** 会话结束：删掉每会话的装配目录（幂等）。 */
  async removeSession(agentKey: string, scope: AssemblyScope & { session: string }): Promise<void> {
    this.rendered.delete(`${agentKey}/${scope.tenant}/${scope.user}/${scope.session}`);
    await rm(join(this.opts.cordisDir, agentKey, scope.tenant, scope.user, scope.session), { recursive: true, force: true }).catch(() => undefined);
  }

  /** 该 scope 的会话持久化根（与 pathFor 同源，池据此授写权限）。 */
  sessionsRootFor(scope?: AssemblyScope): string {
    return scope ? join(this.opts.sessionsRoot, scope.tenant, scope.user) : this.opts.sessionsRoot;
  }

  /** 返回可直接传给 agent 进程的装配文件路径；不存在或过期则重渲染。并发同 key 只渲染一次。 */
  async ensure(agent: AgentRecord, scope?: AssemblyScope): Promise<string> {
    if (this.baseYaml === undefined) throw new Error('CordisCache.init() must be awaited first');
    const path = this.pathFor(agent.agent_key, scope);
    const key = scope ? `${agent.agent_key}/${scope.tenant}/${scope.user}${scope.session ? '/' + scope.session : ''}` : agent.agent_key;
    const skillDirsKey = [(scope?.extraSkillDirs ?? []).join('|'), JSON.stringify(scope?.extraEntries ?? []), scope?.personaSuffix ?? ''].join('#');
    if (this.rendered.get(key) === agent.revision && this.renderedSkillDirs.get(key) === skillDirsKey) return path;
    const pending = this.inflight.get(key);
    if (pending) return pending;
    const task = this.render(agent, path, key, this.sessionsRootFor(scope), scope?.extraSkillDirs ?? [], scope).finally(() => this.inflight.delete(key));
    this.inflight.set(key, task);
    return task;
  }

  private async render(agent: AgentRecord, path: string, key: string, sessionsRoot: string, extraSkillDirs: string[], scope?: AssemblyScope): Promise<string> {
    const text = renderCordis({
      baseYaml: this.baseYaml!,
      agent,
      sessionsRoot,
      ...(this.opts.toolDefaultDeny ? { toolDefaultDeny: this.opts.toolDefaultDeny } : {}),
      ...(this.opts.platformSkillsDir ? { platformSkillsDir: this.opts.platformSkillsDir } : {}),
      skillsDir: this.store.skillsDir(agent.agent_key),
      extraSkillDirs,
      ...(scope?.extraEntries ? { extraEntries: scope.extraEntries } : {}),
      ...(scope?.personaSuffix ? { personaSuffix: scope.personaSuffix } : {}),
    });
    await mkdir(dirname(path), { recursive: true });
    const tmp = `${path}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`;
    await writeFile(tmp, text, 'utf8');
    await rename(tmp, path);
    this.rendered.set(key, agent.revision);
    this.renderedSkillDirs.set(key, [extraSkillDirs.join('|'), JSON.stringify(scope?.extraEntries ?? []), scope?.personaSuffix ?? ''].join('#'));
    return path;
  }
}
