-- Shared employee repository creates an A2A sentinel binding atomically.
CREATE TABLE agent_bus.agent_capability_bindings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 digital_employee_id bigint NOT NULL REFERENCES agent_bus.digital_employees(id),
 agent_version_id bigint REFERENCES agent_bus.agent_versions(id),
 capability_kind varchar(32) NOT NULL CHECK(capability_kind IN ('composer_skill','background_skill','external_skill','mcp','app','a2a_invoke')),
 capability_uuid uuid NOT NULL,
 source varchar(16) NOT NULL CHECK(source IN ('self','borrow')),
 granted_tools varchar(128)[] NOT NULL DEFAULT '{}',
 granted_scopes varchar(64)[] NOT NULL DEFAULT '{}',
 sort_order integer NOT NULL DEFAULT 0,
 pinned boolean NOT NULL DEFAULT false,
 recall_config jsonb NOT NULL DEFAULT '{}',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(digital_employee_id,agent_version_id,capability_kind,capability_uuid)
);
CREATE UNIQUE INDEX idx_acb_draft_unique ON agent_bus.agent_capability_bindings(digital_employee_id,capability_kind,capability_uuid) WHERE agent_version_id IS NULL;
COMMENT ON TABLE agent_bus.agent_capability_bindings IS 'Community shared employee capability bindings; tenant ownership follows digital_employee_id';
