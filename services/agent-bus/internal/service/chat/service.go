// skillParamsMaxBytes — F03 v0.9.1 §10.3 AGBUS_SKILL_PARAMS_MAX_BYTES 默认值。
const skillParamsMaxBytes = 16 * 1024

// buildF03SkillMetadata — F03 v0.9.1 §4.4 user message metadata 透传。
//
// 仅做大小校验；rail-membership 校验留给后续完整 chat-hook 链路接管。
// 任意 active_skill_* 字段非空都会落到 metadata；Bus **不解释** skill_params 字段含义。
func (s *impl) buildF03SkillMetadata(_ context.Context, req SendReq) (map[string]any, error) {
	if req.ActiveSkillUUID == "" && len(req.SkillParams) == 0 &&
		req.ActiveSkillKind == "" && req.ActiveSkillCode == "" {
		return nil, nil
	}
	if len(req.SkillParams) > 0 {
		body, err := json.Marshal(req.SkillParams)
		if err != nil {
			return nil, apperr.ErrInvalidParams.Withf("skill_params not json serializable: %v", err)
		}
		if len(body) > skillParamsMaxBytes {
			return nil, apperr.ErrInvalidParams.Withf("skill.params_too_large: %d bytes > max %d",
				len(body), skillParamsMaxBytes)
		}
	}
	meta := map[string]any{}
	if req.ActiveSkillUUID != "" {
		meta["active_skill_uuid"] = req.ActiveSkillUUID
	}
	if req.ActiveSkillKind != "" {
		meta["active_skill_kind"] = req.ActiveSkillKind
	}
	if req.ActiveSkillBuiltinKey != "" {
		meta["active_skill_builtin_key"] = req.ActiveSkillBuiltinKey
	}
	if req.ActiveSkillCode != "" {
		meta["active_skill_code"] = req.ActiveSkillCode
	}
	if req.ActiveSkillVersion != "" {
		meta["active_skill_version"] = req.ActiveSkillVersion
	}
	if len(req.SkillParams) > 0 {
		meta["skill_params"] = req.SkillParams
	}
	return meta, nil
}

// composerParamsMaxBytes 与 svccomposer.ComposerParamsMaxBytes 一致 (16KB).
// 本地 const 避免 chat 包 import svccomposer (composer 反过来不会 import chat;
// 数值需保持一致, 由测试 enforce 即可).
const composerParamsMaxBytes = 16 * 1024

// buildComposerMetadata Phase A §4.1: 校验 + 组装 user message metadata.
//
//   - 任一字段非空 → composer guard 必须装上, 否则 ErrInternal
//   - 装配命中失败 → apperr.ErrForbidden + Message=chat.skill_not_attached
//   - composer_params 序列化字节 > 16KB → apperr.ErrInvalidParams +
//     Message=chat.composer_params_too_large
//
// 命中后返回 map metadata: composer_skill_uuid / composer_skill_code / composer_params.
// 调用方把它合并到 user message metadata.
func (s *impl) buildComposerMetadata(ctx context.Context, ag *domagent.DigitalEmployee, req SendReq) (map[string]any, error) {
	if req.ComposerSkillUUID == "" && len(req.ComposerParams) == 0 {
		return nil, nil
	}
	if s.composerGuard == nil {
		return nil, apperr.ErrInternal.Withf("chat service missing composer guard; cannot validate composer_skill_uuid")
	}
	if req.ComposerSkillUUID == "" {
		// 只传 composer_params 不传 composer_skill_uuid 没意义, 直接 400.
		return nil, apperr.ErrInvalidParams.Withf("composer_params requires composer_skill_uuid")
	}
	if len(req.ComposerParams) > 0 {
		body, err := json.Marshal(req.ComposerParams)
		if err != nil {
			return nil, apperr.ErrInvalidParams.Withf("composer_params not json serializable: %v", err)
		}
		if len(body) > composerParamsMaxBytes {
			return nil, apperr.ErrInvalidParams.Withf("chat.composer_params_too_large: %d bytes > max %d",
				len(body), composerParamsMaxBytes)
		}
	}
	sk, err := s.composerGuard.AssertSkillAttached(ctx, ag.ID, req.ComposerSkillUUID)
	if err != nil {
		// composer guard 已经返 apperr.ErrForbidden.Withf(...skill_not_attached...);
		// 不再二次包装.
		return nil, err
	}
	meta := map[string]any{
		"composer_skill_uuid": sk.UUID,
		"composer_skill_code": sk.Code,
	}
	if len(req.ComposerParams) > 0 {
		meta["composer_params"] = req.ComposerParams
	}
	return meta, nil
}

