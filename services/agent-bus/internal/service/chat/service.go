// NewWithStopRetry Batch 3B T3.5 生产装配入口: 在 NewWithFanout 基础上注入 stop / retry 依赖.
func NewWithStopRetry(
	logger *log.Logger,
	agents domagent.Repository,
	convs domconv.Repository,
	messages dommsg.Repository,
	runtimes domrt.Repository,
	visibility ContactsVisibility,
	gwClient chatGateway,
	ocResolver openclaw.InstanceResolver,
	fanout Fanout,
	nodeID string,
	deps StopRetryDeps,
) Service {
	base := NewWithFanout(logger, agents, convs, messages, runtimes, visibility, gwClient, ocResolver, fanout, nodeID).(*impl)
	base.streamStore = deps.StreamStore
	base.eventPub = deps.EventPub
	base.txBegin = deps.TxBegin
	// doc-12 Task D 队列：ChatTasks 供 worker/群聊强制队列使用；QueueEnabled 只控制普通聊天。
	base.chatTasks = deps.ChatTasks
	base.readyChecker = deps.ReadyChecker
	base.queueEnabled = deps.QueueEnabled && deps.ChatTasks != nil
	base.queuePerConv = deps.QueuePerConv
	if base.queuePerConv <= 0 {
		base.queuePerConv = 20
	}
	base.queuePerTenant = deps.QueuePerTenant
	if base.queuePerTenant <= 0 {
		base.queuePerTenant = 1000
	}
	// 装齐 orchestration + a2a edge 仓储时仍构造 deorch 执行器（保留装配以便历史隔离 / 后续复用）。
	// 但 P1 (2026-07-08) 起普通聊天不再进入 deorch：Send / RunAgentForConversation / 群聊都不按
	// agent_kind=orchestrator 分流，orchExecutor 因此成为无调用者的 dead code（不再有「对编排型
	// agent fail-closed」这条运行时分支）。准入仍用 EasyO 内部 callable_by_agents 白名单
	// (WhitelistAdmission)；planner 用 AllChildrenPlanner（未接 LLM）。
	if deps.OrchRuns != nil && deps.OrchEdges != nil {
		// P1 返修: 准入用注入的完整 A2A admission; 仅当未注入 (单测白名单子集用例) 才退化为
		// 纯 WhitelistAdmission。生产 (cmd/bus) 必须注入 deorch.A2AAdmission。
		admission := deps.OrchAdmission
		if admission == nil {
			admission = deorch.WhitelistAdmission{}
		}
		base.orchExecutor = deorch.NewExecutor(
			deps.OrchRuns,
			deps.OrchEdges,
			base.AgentInvoker(),
			admission,
			deorch.AllChildrenPlanner{},
			0,   // 用 deorch 默认 time budget
			nil, // 用 deorch noop logger (编排 trace 已落库)
		)
	}
	return base
}

func (s *impl) Send(ctx context.Context, accountID, tenantID int64, req SendReq) (*SendResp, error) {
	if req.AgentUUID == "" || (strings.TrimSpace(req.Text) == "" && len(req.Blocks) == 0) {
		return nil, apperr.ErrInvalidParams
	}
	ag, err := s.agents.GetByUUID(ctx, req.AgentUUID)
	if err != nil {
		return nil, err
	}

	// 可见性收口 (T2D.3-A): chat 能发的 agent 必须 = /contacts/agents 能看到的 agent。
	// 不在此处复制租户/visibility 半截判断, 全部交给 contacts 服务统一裁决, 顺带覆盖
	// contact_enabled / visibility_override / workspace 域 / 平台 agent 隐藏 等隐藏策略。
	// visibility 字段 nil 时 Send 直接拒, 避免任何"忘记装可见性"导致的静默绕过。
	if s.visibility == nil {
		return nil, apperr.ErrInternal.Withf("chat service missing visibility dep")
	}
	if err := s.visibility.AssertAgentVisible(ctx, accountID, tenantID, req.AgentUUID); err != nil {
		return nil, err
	}
	runtimeAccountID, err := runtimeAccountIDForAgent(accountID, ag)
	if err != nil {
		return nil, err
	}

	// P1 (2026-07-08 · plans/2026-07-08-a2a-agent-autonomous-collaboration-fix): 普通聊天主链路
	// 下线 deorch。编排型数字员工不再因 metadata.agent_kind=orchestrator 自动分流到 deorch；
	// 误带该字段的普通数字员工一律走下方 framework 分流的单 Agent runtime 路径。多 Agent 协作
	// 改由 Agent runtime 通过 A2A 工具自主 discover/invoke，Bus 不替 Agent 编排或拼接业务回复。
	// deorch 代码短期保留为无调用者 dead code（有意迁移观察态，见 boundaries §Digital Employee）。

	// 守卫: chat 路径按 runtime_environments.framework 分流:
	//   - openclaw → 走 Gateway v3 WS (T2D.1, 本函数下方 endpoint 解析路径)
	//   - zap      → 走 ZAP HTTP+SSE (Plan 16 Phase 2; 不在 Send 同步解析 endpoint, 由
	//                runAgentInternal/dispatchZapSend 现场解析 + EnsureSession)
	//   - 其它     → fail-closed errProtocolUnsupported
	// 守卫先于 conversation/message 任何持久化, 失败时不残留 user/agent message 行。
	//
	// doc-12 Task D 队列开启时 OpenClaw 路径**不在 Send 同步解析 endpoint/version** (就绪敏感
	// 解析交给 worker), 保证 send 快速返回不被 warming 阻塞; ZAP 路径同理 (EnsureSession 由
	// dispatcher 在 goroutine 里跑)。配置类错误 (无 published version / 非 openclaw/zap / 仓库错)
	// 在这里 / 在 worker 标 failed 出 chat.runtime_protocol_unsupported, 不伪装成功。
	framework, ferr := s.frameworkForAgent(ctx, ag, s.runtimeEnvFW)
	if ferr != nil {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Wrap(ferr)
	}
	var (
		ep        gatewayws.Endpoint
		verParams *versionParams
	)
	if !s.queueEnabled && framework == FrameworkOpenClaw {
		var rerr error
		ep, _, rerr = s.resolveOpenClawV3Endpoint(ctx, tenantID, runtimeAccountID, ag)
		if rerr != nil {
			// runtime.warming (实例未就绪, 暂时态) 与 protocol_unsupported (配置错) 分两个 code 透出,
			// 客户端 503 runtime.warming 走 retry / 显示"准备中"; protocol_unsupported 走错误 toast。
			if errors.Is(rerr, errRuntimeNotReady) {
				return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeRuntimeWarming).Wrap(rerr)
			}
			return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Wrap(rerr)
		}
		// 真实版本快照装载 (T2D.3-B): chat.send 主参数来自 agent_versions.snapshot,
		// 不再用 digital_employees 上的临时字段。fail-closed: current_version 缺失 /
		// snapshot 缺失 / 缺 model 一律 5xx, 不写 conv/msg, 不启动 stream goroutine。
		verParams, rerr = s.loadVersionParams(ctx, ag)
		if rerr != nil {
			return nil, rerr
		}
	}
	if !s.queueEnabled && isZapWireFramework(framework) {
		// ZAP 路径要求 identity resolver + zap dispatcher 装齐; 否则 Send 直接拒,
		// 不写 conv/msg/stream (与 openclaw 装配缺失等价口径)。
		if s.identityResolver == nil || s.zapDispatcher == nil {
			return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
				Withf("zap framework dispatch not wired")
		}
	}
	if !s.queueEnabled && framework == FrameworkHermes {
		if s.hermesDispatcher == nil {
			return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
				Withf("hermes framework dispatch not wired")
		}
	}
	if framework == FrameworkGeneric && s.genericRuntime == nil {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Withf("generic runtime not wired")
	}
	if framework != FrameworkOpenClaw && !isZapWireFramework(framework) && framework != FrameworkHermes && framework != FrameworkSupportBuiltin && framework != FrameworkGeneric {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
			Withf("framework %q chat not implemented", framework)
	}

	// M6 Phase A: 校验 composer_skill_uuid 装配命中 + params 上限. 校验在 conversation
	// 解析 / user message 写入之前进行 — 失败时 user message 一行不写.
	composerMeta, err := s.buildComposerMetadata(ctx, ag, req)
	if err != nil {
		return nil, err
	}
	if ag.ExecutionLocus != "local" && strings.TrimSpace(req.ModelHint) != "" {
		selected := strings.TrimSpace(req.ModelHint)
		if err := s.validateConversationModel(ctx, accountID, tenantID, ag, framework, selected); err != nil {
			return nil, err
		}
		if composerMeta == nil {
			composerMeta = map[string]any{}
		}
		composerMeta["conversation_model"] = selected
		if verParams != nil {
			verParams.SelectedModel = selected
		}
	}
	if ag.ExecutionLocus == "local" {
		if s.localRuntime == nil || req.LocalLoginSessionUUID == "" || !canRunOnCallersComputer(ag, accountID) {
			return nil, apperr.New(apperr.PreconditionFailed, "chat.local_unavailable")
		}
		caller := domlocal.Scope{AccountID: accountID, TenantID: tenantID, SessionUUID: req.LocalLoginSessionUUID}
		device, err := s.localRuntime.ResolveDesktop(ctx, caller, req.LocalDeviceUUID)
		if errors.Is(err, domlocal.ErrUpgradeRequired) {
			return nil, apperr.New(apperr.PreconditionFailed, "chat.local_upgrade_required")
		}
		if err != nil {
			return nil, apperr.New(apperr.PreconditionFailed, "chat.local_offline")
		}
		model, err := s.localRuntime.Ready(ctx, device.Scope, device.UUID, ag.ID, req.ModelHint)
		if err != nil {
			if errors.Is(err, domsource.ErrConfiguration) {
				return nil, apperr.New(apperr.PreconditionFailed, "chat.model_configuration_unavailable")
			}
			if errors.Is(err, domlocal.ErrOffline) {
				return nil, apperr.New(apperr.PreconditionFailed, "chat.local_offline")
			}
			return nil, apperr.New(apperr.PreconditionFailed, "chat.model_unavailable")
		}
		if composerMeta == nil {
			composerMeta = map[string]any{}
		}
		source := "desktop"
		if caller.SessionUUID != device.Scope.SessionUUID {
			source = "mobile"
		}
		// A mobile caller cannot select a desktop filesystem context.
		if source == "desktop" && req.LocalContextID != "" {
			if _, err := uuid.Parse(req.LocalContextID); err != nil {
				return nil, apperr.ErrInvalidParams.Withf("本机工作目录上下文无效")
			}
			composerMeta["local_context_id"] = req.LocalContextID
		}
		composerMeta["local_task_source"] = source
		composerMeta["local_requester_session_id"] = caller.SessionUUID
		composerMeta["local_device_id"] = device.UUID
		composerMeta["local_login_session_id"] = device.Scope.SessionUUID
		composerMeta["local_model_hint"] = model
	}
	// F03 v0.9.1 §4.4: active_skill_* / skill_params 透传到 user message metadata。
	skillF03Meta, err := s.buildF03SkillMetadata(ctx, req)
	if err != nil {
		return nil, err
	}
	if len(skillF03Meta) > 0 {
		if composerMeta == nil {
			composerMeta = map[string]any{}
		}
		for k, v := range skillF03Meta {
			composerMeta[k] = v
		}
	}

	// 1. 获取或创建 conversation (T2D.2)
	conv, err := s.resolveOrCreateConversation(ctx, accountID, tenantID, ag, req)
	if err != nil {
		return nil, err
	}

	// 1.5 (doc-12 Task D 队列) backlog 硬限 **fail-closed, 在写 user 消息之前** —— 超限/计数出错时
	// 直接返错, **不写 user 消息、不写 agent 预留、不入队** (避免 API 失败后残留半状态 user message)。
	if s.queueEnabled && s.chatTasks != nil && ag.ExecutionLocus != "local" {
		if err := s.checkChatQueueBudget(ctx, tenantID, conv.ID); err != nil {
			return nil, err
		}
	}

	// 2. 写 user message. 附件路径先校验/取元数据并把 image/file block 写入
	// messages.blocks, 再绑定 CMF; blocks 是历史展示真相, CMF 是权限/runtime 真相。
	userBlocks := req.Blocks
	if len(userBlocks) == 0 && req.Text != "" {
		userBlocks = []map[string]any{{"type": "plain", "text": req.Text}}
	}
	var resolvedAttachments []messageblocks.Attachment
	preUserUUID := ""
	if len(req.FileUUIDs) > 0 {
		if s.attachments == nil {
			return nil, apperr.ErrInternal.Withf("chat service missing attachment binder; cannot bind file_uuids")
		}
		resolvedAttachments, err = s.attachments.ResolveForMessage(ctx, accountID, tenantID, req.FileUUIDs)
		if err != nil {
			return nil, err
		}
		userBlocks = messageblocks.AppendAttachments(userBlocks, resolvedAttachments)
		preUserUUID = id.NewUUID()
	}
	userMsg, err := s.messages.Append(ctx, &dommsg.Message{
		UUID:            preUserUUID, // 空 → repo 走 gen_random_uuid()
		TenantID:        tenantID,
		ConversationID:  conv.ID,
		Role:            "user",
		SenderAccountID: &accountID,
		Blocks:          userBlocks,
		Status:          "final",
		Final:           true,
		Metadata:        composerMeta,
	})
	if err != nil {
		return nil, err
	}
	if len(resolvedAttachments) > 0 {
		if err := s.attachments.BindToMessage(ctx, accountID, tenantID, userMsg.UUID, req.FileUUIDs); err != nil {
			return nil, err
		}
	}
	// 3. 调低层 runAgentInternal: 写 streaming agent 预留 + register stream + (queue on) 入队 / (off) spawn goroutine。
	// queue on: UserMessageUUID 非空 → 入队 (worker 据此回读正文取 prompt, 任务不存正文); BudgetChecked=true (上面 1.5 已查)。
	out, err := s.runAgentInternal(ctx, runAgentInternalIn{
		AccountID:        accountID,
		RuntimeAccountID: runtimeAccountID,
		TenantID:         tenantID,
		Conversation:     conv,
		RoomUUID:         "", // single-chat
		Agent:            ag,
		PromptText:       req.Text,
		UserBlocks:       userBlocks,
		SkillSlugs:       skillSlugsFromBlocks(userBlocks),
		Framework:        framework,
		Endpoint:         ep,
		VerParams:        verParams,
		UserMessageUUID:  userMsg.UUID,
		InputMessageUUID: userMsg.UUID,
		UserMetadata:     composerMeta,
		BudgetChecked:    true,
	})
	if err != nil {
		return nil, err
	}
	return &SendResp{
		ConversationUUID: conv.UUID,
		StreamID:         out.StreamID,
		UserMessageUUID:  userMsg.UUID,
		AgentMessageUUID: out.AgentMessageUUID,
	}, nil
}

// RunAgentForConversation Batch 2E T2E.4: 暴露给 room.Service 桥接群聊用。
//
// 关键纪律:
//   - 调用方必须**已写好** user message 并 commit (group: 在 room.SendMessage 自己的 tx 里)
//   - 调用方必须已校验 caller 在 room 内 + agent 仍 active (selector 命中即代表 active)
//   - 本方法只负责 agent streaming 链路, 不写 user message, 不重复 visibility 校验
//
// 内部走与 Send 相同的 runAgentInternal, 因此守卫 / verParams / hub / SSE event 行为完全一致。
func (s *impl) RunAgentForConversation(ctx context.Context, in RunAgentInput) (*RunAgentOutput, error) {
	if in.Conversation == nil || in.Agent == nil {
		return nil, apperr.ErrInvalidParams.Withf("RunAgentForConversation: conversation/agent required")
	}
	runtimeAccountID, err := runtimeAccountIDForAgent(in.AccountID, in.Agent)
	if err != nil {
		return nil, err
	}
	if in.StartFailureCause != nil {
		failure := classifyRunStartFailure(in.StartFailureCause)
		framework, _ := s.frameworkForAgent(ctx, in.Agent, s.runtimeEnvFW)
		out, err := s.runAgentInternal(ctx, runAgentInternalIn{
			AccountID:        in.AccountID,
			RuntimeAccountID: runtimeAccountID,
			TenantID:         in.TenantID,
			Conversation:     in.Conversation,
			RoomUUID:         in.RoomUUID,
			Agent:            in.Agent,
			Framework:        framework,
			StartFailure:     &failure,
		})
		if err != nil {
			return nil, err
		}
		return &RunAgentOutput{StreamID: out.StreamID, AgentMessageUUID: out.AgentMessageUUID}, nil
	}
	// RunAgentForConversation 现在有三类调用方:
	//   1. agent-direct WuKong (RoomUUID 为空, 但 conversation 可能绑定 room): 按 single-chat
	//      语义复用 Send 的 ZAP dispatcher。
	//   2. group room — OpenClaw: 现状路径不变。
	//   3. group room — ZAP (round-8 起): 同样走 ZAP dispatcher (single-Agent 视角:
	//      runtime 只看到"这条 user message → 这一轮 assistant 回复", 与单聊场景对称;
	//      多 Agent 编排 / A2A **不**在本轮范围)。
	//
	// 权限/可见性守卫**不**在本层校验, 一律由 caller (room.Service.SendMessage 上游
	// 已校验 caller 在 room + agent 仍 active + selector 命中) 兜底; 本层只做 framework
	// 分流的 fail-closed (避免错给非 OpenClaw/ZAP runtime).
	//
	// P1 (2026-07-08 · plans/2026-07-08-a2a-agent-autonomous-collaboration-fix): 群聊 /
	// agent-direct 命中 metadata.agent_kind=orchestrator 也不再自动分流到 deorch；一律按单 Agent
	// runtime 处理。多 Agent 协作改由 runtime 通过 A2A 工具自主发起，Bus 不替 Agent 编排或拼接
	// 回复。deorch 代码短期保留为无调用者 dead code（与 /chat/send 同口径）。

	// framework 解析失败 / 非支持组合 → fail-closed errProtocolUnsupported, 不写流。
	framework, ferr := s.frameworkForAgent(ctx, in.Agent, s.runtimeEnvFW)
	if ferr != nil {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Wrap(ferr)
	}
	if framework == FrameworkGeneric && s.genericRuntime == nil {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Withf("generic runtime not wired")
	}
	if framework != FrameworkOpenClaw && !isZapWireFramework(framework) && framework != FrameworkHermes && framework != FrameworkSupportBuiltin && framework != FrameworkGeneric {
		if in.RoomUUID != "" {
			return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
				Withf("group room runtime framework %q chat not supported", framework)
		}
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
			Withf("single runtime framework %q chat not supported", framework)
	}
	if isZapWireFramework(framework) && (s.identityResolver == nil || s.zapDispatcher == nil) {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
			Withf("zap framework dispatch not wired")
	}
	if framework == FrameworkHermes && s.hermesDispatcher == nil {
		return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).
			Withf("hermes framework dispatch not wired")
	}
	internalIn := runAgentInternalIn{
		AccountID:        in.AccountID,
		RuntimeAccountID: runtimeAccountID,
		TenantID:         in.TenantID,
		Conversation:     in.Conversation,
		RoomUUID:         in.RoomUUID,
		Agent:            in.Agent,
		PromptText:       in.PromptText,
		SkillSlugs:       in.SkillSlugs,
		Framework:        framework,
		UserMessageUUID:  in.UserMessageUUID,
		InputMessageUUID: firstNonEmpty(in.InputMessageUUID, in.UserMessageUUID),
		ForceQueue:       in.ForceQueue,
	}
	if in.Agent.ExecutionLocus == "local" && in.CronRunUUID != "" {
		metadata, err := s.prepareScheduledLocalChat(ctx, in)
		if err != nil {
			return nil, err
		}
		internalIn.UserMetadata = metadata
	}
	// doc-12 Task D: queue on **且** 调用方提供了 UserMessageUUID → 不同步解析 endpoint/version (就绪敏感),
	// 直接传零值, 由 worker executeQueuedTask 现场重解析 + CheckReady defer。否则 (queue off, 或 composed-prompt
	// 调用方 room/cron/wukong trigger 未传 UserMessageUUID → 无法据 uuid 回读正文) 保持现状: 同步解析 + 进程内 goroutine。
	queued := s.useQueue(internalIn)
	if !queued && internalIn.InputMessageUUID != "" && s.messages != nil {
		if inputMsg, err := s.messages.GetByUUID(ctx, internalIn.InputMessageUUID); err != nil {
			s.logger.Warn(ctx, "chat zap input message lookup failed",
				"message_uuid", internalIn.InputMessageUUID, "err", err.Error())
		} else if inputMsg == nil ||
			inputMsg.TenantID != in.TenantID ||
			inputMsg.ConversationID != in.Conversation.ID ||
			inputMsg.SenderAccountID == nil ||
			*inputMsg.SenderAccountID != in.AccountID {
			s.logger.Warn(ctx, "chat zap input message ignored",
				"message_uuid", internalIn.InputMessageUUID, "reason", "scope_mismatch")
		} else {
			internalIn.UserBlocks = cloneZapOutboundBlocks(inputMsg.Blocks)
			internalIn.SkillSlugs = append(internalIn.SkillSlugs, skillSlugsFromBlocks(inputMsg.Blocks)...)
			if model := selectedConversationModel(inputMsg.Metadata); model != "" {
				if err := s.validateConversationModel(ctx, in.AccountID, in.TenantID, in.Agent, framework, model); err != nil {
					return nil, err
				}
				internalIn.UserMetadata = map[string]any{"conversation_model": model}
			}
		}
	}
	if !queued && framework == FrameworkOpenClaw {
		// ADR-0037: 同步(非 queue)路径此前只读 resolveOpenClawV3Endpoint, 实例被外部
		// 删除/回收后不会自愈——一直报 runtime_warming 也不会有任何东西触发重新 provision。
		// queue.go 的 executeQueuedTask 已有这一步 (2) 就绪检查+自愈, 这里补齐同一逻辑,
		// 覆盖 wukong agent-direct 等不带 UserMessageUUID、走同步路径的调用方。
		if s.readyChecker != nil && in.Agent.RuntimeEnvironmentID != nil && *in.Agent.RuntimeEnvironmentID > 0 {
			var readyAgentUUID *string
			if in.Agent.ModelSource == "byok" {
				readyAgentUUID = &in.Agent.UUID
			}
			ready, status, _, cerr := s.readyChecker.CheckReady(ctx, in.TenantID, runtimeAccountID, *in.Agent.RuntimeEnvironmentID, readyAgentUUID)
			if cerr == nil && !ready {
				return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeRuntimeWarming).
					Withf("runtime instance not ready (status=%s)", status)
			}
		}
		ep, _, err := s.resolveOpenClawV3Endpoint(ctx, in.TenantID, runtimeAccountID, in.Agent)
		if err != nil {
			if errors.Is(err, errRuntimeNotReady) {
				return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeRuntimeWarming).Wrap(err)
			}
			return nil, apperr.New(apperr.UpstreamUnavailable, ErrCodeProtocolUnsupported).Wrap(err)
		}
		verParams, err := s.loadVersionParams(ctx, in.Agent)
		if err != nil {
			return nil, err
		}
		internalIn.Endpoint = ep
		verParams.SelectedModel = selectedConversationModel(internalIn.UserMetadata)
		internalIn.VerParams = verParams
	}
	out, err := s.runAgentInternal(ctx, internalIn)
	if err != nil {
		return nil, err
	}
	return &RunAgentOutput{StreamID: out.StreamID, AgentMessageUUID: out.AgentMessageUUID}, nil
}

func (s *impl) orchestratorPromptFromRunInput(ctx context.Context, in RunAgentInput) (string, []map[string]any) {
	inputUUID := firstNonEmpty(in.InputMessageUUID, in.UserMessageUUID)
	if inputUUID == "" || s.messages == nil {
		return in.PromptText, nil
	}
	inputMsg, err := s.messages.GetByUUID(ctx, inputUUID)
	if err != nil {
		s.logger.Warn(ctx, "chat orchestrator input message lookup failed",
			"message_uuid", inputUUID, "err", err.Error())
		return in.PromptText, nil
	}
	if inputMsg == nil ||
		inputMsg.TenantID != in.TenantID ||
		inputMsg.ConversationID != in.Conversation.ID ||
		inputMsg.SenderAccountID == nil ||
		*inputMsg.SenderAccountID != in.AccountID {
		s.logger.Warn(ctx, "chat orchestrator input message ignored",
			"message_uuid", inputUUID, "reason", "scope_mismatch")
		return in.PromptText, nil
	}
	blocks := cloneZapOutboundBlocks(inputMsg.Blocks)
	prompt := orchPromptText("", blocks)
	if strings.TrimSpace(prompt) == "" {
		return in.PromptText, blocks
	}
	return prompt, blocks
}

