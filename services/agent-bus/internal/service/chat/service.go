// checkChatQueueBudget (doc-12 Task D) 入队前 backlog 硬限 (单会话 queued+running ≥N / 单租户 ≥M)。
// **fail-closed**: CountActive* 查询出错时**拒绝**入队 (返回 ErrInternal), 不放行造成无界堆积或绕过限额。
// 直连 Send 在写 user 消息前调用 → 超限/出错时 user 消息一行不写; runAgentInternal 对其它入队方兜底再调一次。
func (s *impl) checkChatQueueBudget(ctx context.Context, tenantID, conversationID int64) error {
	n, err := s.chatTasks.CountActiveByConversation(ctx, conversationID)
	if err != nil {
		return apperr.ErrInternal.Wrap(err)
	}
	if n >= s.queuePerConv {
		return apperr.New(apperr.InvalidParams, "chat.too_many_pending")
	}
	n, err = s.chatTasks.CountActiveByTenant(ctx, tenantID)
	if err != nil {
		return apperr.ErrInternal.Wrap(err)
	}
	if n >= s.queuePerTenant {
		return apperr.New(apperr.TooManyRequests, "chat.tenant_backlog_exceeded")
	}
	return nil
}

// runAgentInternal 写 streaming agent 预留 + register stream + spawn goroutine (单聊和群聊共用)。
//
// rework #2: 群消息时, agent streaming message 必须与 user message 一致写入 room_id;
// 否则 GET /rooms/{uuid}/messages 拿不到 agent 回复 (查询条件含 room_id)。
// in.Conversation.RoomID 不为 nil 时直接复用; 单聊场景 RoomID 为 nil, schema 允许 NULL。
//
// Batch 3A T3.1: pub *publisher 已下线, 改通过 s.fanout.Publish(ctx, streamID, accountID, ...)
// 投递; Register 写 stream owner + bus_node_id 到 fanout (RedisFanout 用 HASH, LocalFanout
// 用进程内 map). nodeID 取自 s.nodeID, 跨节点 stop 路径 (T3.5) 据此查 owner.
//
// 3A 返修 #4 (fail-closed): 顺序是 Register → Append → Publish(created). Register 失败
// 直接返回 error, **不写消息行, 不启 goroutine**, 防止 /chat/stream?stream_id=...
// 兼容端点查 owner 失败 (owner 在 fanout 里, 而 stream 已经存在). Append 失败则尝试
// fanout.Close 收尾 register, 再向上抛错.
func (s *impl) runAgentInternal(ctx context.Context, in runAgentInternalIn) (*runAgentInternalOut, error) {
	if in.RuntimeAccountID <= 0 {
		var err error
		in.RuntimeAccountID, err = runtimeAccountIDForAgent(in.AccountID, in.Agent)
		if err != nil {
			return nil, err
		}
	}
	if in.ForceQueue && (s.chatTasks == nil || strings.TrimSpace(in.UserMessageUUID) == "") {
		return nil, apperr.ErrInternal.Withf("chat forced queue missing task repository or user message anchor")
	}
	in.PromptText = promptTextWithSkillSlugs(in.PromptText, in.SkillSlugs)

	// Step 0 (doc-12 Task D 队列) — backlog 硬限 (创建前预算; 预建消息前先挡, 避免 streaming 僵尸)。
	// Send 已在写 user 消息前查过 (BudgetChecked=true) → 跳过; RunAgentForConversation 等其它入队方在此查。
	// **fail-closed**: 计数出错不放行 (见 checkChatQueueBudget)。
	if s.useQueue(in) && !in.BudgetChecked {
		if err := s.checkChatQueueBudget(ctx, in.TenantID, in.Conversation.ID); err != nil {
			return nil, err
		}
	}

	streamID, _ := id.RandomHex(16)
	cancelToken, _ := id.RandomHex(16)

	// Step 1 — Register stream owner 到 fanout. 失败即 fail-fast (Codex review #4).
	// Register 必须先于 messages.Append, 这样失败时不留 orphan agent message 行.
	if err := s.fanout.Register(ctx, streamID, in.AccountID, in.TenantID, s.nodeID); err != nil {
		s.logger.Warn(ctx, "chat fanout register failed (aborting send)", "stream_id", streamID, "err", err)
		return nil, apperr.ErrInternal.Wrap(err)
	}

	// Step 2 — 写 streaming agent 预留行.
	agentMsg, err := s.messages.Append(ctx, &dommsg.Message{
		TenantID:       in.TenantID,
		ConversationID: in.Conversation.ID,
		RoomID:         in.Conversation.RoomID, // T2E rework #2: 群消息透传 room_id
		Role:           "agent",
		SenderAgentID:  &in.Agent.ID,
		Blocks:         []map[string]any{},
		Status:         "streaming",
		StreamID:       streamID,
	})
	if err != nil {
		// 已 Register 但 Append 失败 → 显式 Close 让 fanout 释放 owner meta (避免脏 stream).
		s.fanout.Close(ctx, streamID)
		return nil, err
	}

	// Step 2.5 (Batch 3B T3.5) — 写 message_streams 行, 记 owner_node + cancel_token.
	// 这一步在 messages.Append 之后是因为 message_streams.message_uuid 是 UNIQUE 索引
	// 且引用 agentMsg.UUID; 但仍然 fail-closed: INSERT 失败时收尾 (UpdateStream 标 failed
	// + emit message.failed + 关 fanout), 不启 goroutine.
	//
	// streamStore 为 nil 时跳过 (兼容旧单测路径); cmd/bus 走 NewWithStopRetry 总会装上.
	if s.streamStore != nil {
		if _, err := s.streamStore.Insert(ctx, dommstream.CreateInput{
			StreamID:       streamID,
			TenantID:       in.TenantID,
			AccountID:      in.AccountID,
			ConversationID: in.Conversation.ID,
			MessageUUID:    agentMsg.UUID,
			CancelToken:    cancelToken,
			BusNodeID:      s.nodeID,
		}); err != nil {
			s.logger.Error(ctx, "chat message_streams insert failed (aborting send)",
				"stream_id", streamID, "err", err)
			// 把 agent message 标 failed, 让消费方看到一致终态.
			_ = s.messages.UpdateStream(context.Background(), streamID,
				[]map[string]any{}, "failed", true, "chat.stream_store_failed", err.Error(), nil)
			s.fanout.Close(ctx, streamID)
			return nil, apperr.ErrInternal.Wrap(err)
		}
	}

	// Step 3 — T2D.5 SSE: 在 spawn goroutine 之前发 message.created, RoomUUID 在群聊时非空 (T2E.6).
	// Publish 失败不算致命 (XADD/PUBLISH 任一异常都会让客户端走 fallback 拉 history),
	// 仅日志; 但 owner / stream 已建立, 客户端可以连上去等终态.
	if err := s.fanout.Publish(ctx, streamID, in.AccountID, in.TenantID, StreamEvent{
		Kind:             EventMessageCreated,
		ConversationUUID: in.Conversation.UUID,
		RoomUUID:         in.RoomUUID,
		MessageUUID:      agentMsg.UUID,
		Role:             "agent",
		StreamID:         streamID,
		Timestamp:        time.Now(),
	}); err != nil {
		s.logger.Warn(ctx, "chat fanout publish created failed", "stream_id", streamID, "err", err)
	}

	if in.StartFailure != nil {
		failure := *in.StartFailure
		s.startRunRecorder(ctx, RunSpec{
			TenantID:          in.TenantID,
			AccountID:         in.AccountID,
			DigitalEmployeeID: in.Agent.ID,
			ConversationUUID:  in.Conversation.UUID,
			MessageUUID:       agentMsg.UUID,
			StreamID:          streamID,
			RoomID:            in.Conversation.RoomID,
			RuntimeKind:       runtimeKindFromFramework(in.Framework),
			// Pre-dispatch failures can belong to either locus (dsh runs both), so
			// take it from the employee record rather than guessing from the framework.
			ExecutionLocus:       in.Agent.ExecutionLocus,
			RuntimeEnvironmentID: in.Agent.RuntimeEnvironmentID,
			TriggerSource:        zapTriggerSource(in.RoomUUID),
			AgentVersion:         in.Agent.CurrentVersion,
		})
		s.logRuntimeFailureDiagnostic(ctx, runtimeFailureDiagnosticInput{
			RuntimeKind:      in.Framework,
			FailureStage:     "start_failure",
			StreamID:         streamID,
			MessageUUID:      agentMsg.UUID,
			ConversationUUID: in.Conversation.UUID,
			RoomUUID:         in.RoomUUID,
			AccountID:        in.AccountID,
			TenantID:         in.TenantID,
			Agent:            in.Agent,
			ErrorCode:        failure.code,
			Diagnostic:       failure.diagnostic,
		})
		go func() {
			finalizeCtx := context.Background()
			defer s.fanout.Close(finalizeCtx, streamID)
			s.finalize(finalizeCtx, streamID, in.AccountID, in.TenantID,
				in.Conversation.UUID, in.RoomUUID, agentMsg.UUID,
				[]map[string]any{{"type": "markdown", "text": failure.text}},
				"failed", failure.code, failure.text, nil)
		}()
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}

	// Step 4 — 异步跑 runtime: ctx.Background 同 batch 2D 取舍 (req ctx 在 HTTP 收尾后会取消, 但
	// chat goroutine 必须跑到 LLM 完成). Publish 内部各自带短 ctx 超时.
	//
	// 3B T3.5 + 返修 #1: 装一个 WithCancelCause ctx, 把 cancelFunc 登记到 activeStreams.
	// Stop / cancel listener 触发它时传 ErrStopByUser → processFramesV3 据此 finalize
	// 'cancelled' 而不是 'final', 防止 stop 后还冒出 message.completed.
	//
	// activeStreams 由 NewWithFanout 总会初始化, 永远非 nil; 但保险起见, nil 路径下也
	// 必须调用 streamCancel (defer 自我守卫), 防止 ctx 泄漏 (go vet 也强制这个不变量).
	// Step 4 (doc-12 Task D 队列) — queue 开启: 预建消息 + stream + message.created 已就绪 (客户端可立即订阅);
	// **入队任务由 worker 异步消费** (ExecuteQueuedTask 复用本节点等价执行), 不在本进程 go runAgentGoroutine。
	// fanout owner / message_streams.bus_node_id 暂记本节点; worker 消费时切到执行节点 (UpdateOwnerNode + 重 Register)。
	// Step 4 (doc-14 Objective E / P1 编排) — 编排型数字员工: 预建消息 + stream 已就绪 (客户端可立即订阅),
	// detached goroutine 跑 deorch.Executor。编排**不入队** (worker 不识别编排任务), 也不走单体 runtime;
	// child 调用经 AgentInvoker 同步排空, run/step/edge trace 落库, 完成后 finalize 出唯一一条编排回复。
	// 装了 cancel token → stop 可中断 (与单体一致)。
	if in.OrchestratorStrategy != "" {
		streamCtx, streamCancel := context.WithCancelCause(context.Background())
		if s.activeStreams == nil {
			streamCancel(nil)
			s.fanout.Close(ctx, streamID)
			return nil, apperr.ErrInternal.Withf("chat.activeStreams not wired")
		}
		s.activeStreams.put(streamID, activeStreamEntry{
			cancel:      streamCancel,
			messageUUID: agentMsg.UUID,
			tenantID:    in.TenantID,
			accountID:   in.AccountID,
		})
		go s.runOrchestratorGoroutine(streamCtx, streamID, in, agentMsg.UUID)
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}

	if s.useQueue(in) {
		_, err := s.chatTasks.Enqueue(ctx, domchattask.EnqueueInput{
			TenantID:         in.TenantID,
			AccountID:        in.AccountID,
			ConversationID:   in.Conversation.ID,
			ConversationUUID: in.Conversation.UUID,
			RoomUUID:         in.RoomUUID,
			AgentUUID:        in.Agent.UUID,
			AgentMessageUUID: agentMsg.UUID,
			StreamID:         streamID,
			UserMessageUUID:  in.UserMessageUUID, // 不复制正文; worker 据此回读 messages 取 prompt
		})
		if err != nil && err != apperr.ErrConflict {
			// 入队失败 → 预建消息标 failed (不留 streaming 僵尸), 客户端收 failed; 内部错误码不下发。
			_ = s.messages.UpdateStream(context.Background(), streamID, []map[string]any{}, "failed", true, "chat.enqueue_failed", "", nil)
			s.fanout.Close(ctx, streamID)
			return nil, apperr.ErrInternal.Wrap(err)
		}
		// ErrConflict = 幂等 (同 agent_message 已入队), 视为成功。
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}

	// 现状同步路径 (queue 关): 本进程 detached goroutine 直接执行。
	streamCtx, streamCancel := context.WithCancelCause(context.Background())
	if s.activeStreams == nil {
		// 不应该发生; 出现说明 chat.Service 构造路径漏装 registry. fail-closed.
		streamCancel(nil)
		s.fanout.Close(ctx, streamID)
		return nil, apperr.ErrInternal.Withf("chat.activeStreams not wired")
	}
	s.activeStreams.put(streamID, activeStreamEntry{
		cancel:      streamCancel,
		messageUUID: agentMsg.UUID,
		tenantID:    in.TenantID,
		accountID:   in.AccountID,
	})
	// Plan 16 Phase 2 — framework dispatch: ZAP → 走 runZapChatGoroutine (EnsureSession + SSE);
	// 默认 / openclaw → 原 Gateway v3 WS 路径。Framework 字段在 Send / RunAgentForConversation
	// 入口填入; 空字符串 / 其它值在 Send 入口已 fail-closed, 这里只兜底分流。
	if isZapWireFramework(in.Framework) {
		go s.runZapChatGoroutine(streamCtx, streamID, in.AccountID, in.TenantID,
			in.Conversation, in.RoomUUID, in.Agent, in.PromptText, in.UserBlocks,
			agentMsg.UUID, in.UserMessageUUID, in.InputMessageUUID, in.UserMetadata)
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}
	if in.Framework == FrameworkGeneric {
		go s.runGenericRuntime(streamCtx, streamID, in, agentMsg.UUID)
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}
	if in.Framework == FrameworkHermes {
		go s.runHermesChatGoroutine(streamCtx, streamID, in.AccountID, in.RuntimeAccountID, in.TenantID,
			in.Conversation, in.RoomUUID, in.Agent, in.PromptText, agentMsg.UUID, in.UserMessageUUID, in.InputMessageUUID, selectedConversationModel(in.UserMetadata))
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}
	if in.Framework == FrameworkSupportBuiltin {
		go s.runSupportResponderGoroutine(streamCtx, streamID, in, agentMsg.UUID)
		return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
	}
	go s.runAgentGoroutine(streamCtx, streamID, in.AccountID, in.RuntimeAccountID, in.TenantID,
		in.Endpoint, in.Agent, in.PromptText, in.Conversation.UUID, in.RoomUUID,
		agentMsg.UUID, in.VerParams, in.InputMessageUUID)

	return &runAgentInternalOut{StreamID: streamID, AgentMessageUUID: agentMsg.UUID}, nil
}

// resolveOrCreateConversation Batch 2D T2D.2: chat.Send 的 conversation 选取/创建语义。
//
// 两条分支:
//
//  1. req.ConversationUUID != ""  → 校验 conversation 归属 + agent 一致性
//     a. tenant_id 必须匹配
//     b. account_id 必须匹配 (其它账号不能拿别人的 conversation_uuid 发消息)
//     c. digital_employee_id 必须 = ag.ID (拿 A agent_uuid 往 B agent 的 conversation 里发 → 403)
//     d. room_id 必须为 NULL (走 chat.send 入口的会话必须是 single-chat, 群聊路径走 rooms API)
//     任意失败 → apperr.ErrForbidden, 不写任何 message
//
//  2. req.ConversationUUID == ""  → 复用或新建
//     a. FindActiveSingle(tenantID, accountID, ag.ID) 命中 → 直接复用 (用户"再开一次"自动落老会话)
//     b. ErrNotFound → Create 新 conversation
//     c. 其它 DB 错误 → 透传
//
// 显式新会话 (archive 旧的 + 建新) / pinned / archived 等留 M4 完整版。
func (s *impl) resolveOrCreateConversation(
	ctx context.Context,
	accountID, tenantID int64,
	ag *domagent.DigitalEmployee,
	req SendReq,
) (*domconv.Conversation, error) {
	if req.ConversationUUID != "" {
		conv, err := s.convs.GetByUUID(ctx, req.ConversationUUID)
		if err != nil {
			return nil, err
		}
		if conv.TenantID != tenantID {
			return nil, apperr.ErrForbidden.Withf("conversation tenant mismatch")
		}
		if conv.AccountID != accountID {
			return nil, apperr.ErrForbidden.Withf("conversation account mismatch")
		}
		if conv.RoomID != nil {
			// 群聊 conversation 不允许走 chat.send (这条入口仅服务 single-chat)
			return nil, apperr.ErrForbidden.Withf("conversation belongs to a room; use rooms API")
		}
		if conv.DigitalEmployeeID == nil || *conv.DigitalEmployeeID != ag.ID {
			return nil, apperr.ErrForbidden.Withf("conversation agent mismatch")
		}
		return conv, nil
	}

	// 复用语义: 同 (tenant, account, agent) 维度只允许一条活跃 single-chat。
	//
	// 流程: FindActiveSingle 命中即复用; ErrNotFound 走 Create; 其它 DB 错透传。
	//
	// 并发兜底 (T2D.9): 两条 Send 同时落 Create 时, T2D.9 partial unique index
	// (idx_conv_single_active_v2d) 让第二条 INSERT 失败 → Postgres SQLSTATE 23505 →
	// 这里捕获后回查 FindActiveSingle 复用第一条胜出的 conversation, 不向上吐 500。
	existing, err := s.convs.FindActiveSingle(ctx, tenantID, accountID, ag.ID)
	if err == nil {
		return existing, nil
	}
	if !errors.Is(err, apperr.ErrNotFound) {
		return nil, err
	}
	created, err := s.convs.Create(ctx, &domconv.Conversation{
		TenantID:          tenantID,
		AccountID:         accountID,
		DigitalEmployeeID: &ag.ID,
		Title:             firstLine(req.Text),
		Source:            "chat",
	})
	if err == nil {
		return created, nil
	}
	if !isUniqueViolation(err) {
		return nil, err
	}
	// 并发竞态: 别的 Send 抢先 Create 完了; 回查复用。
	// 极端情况下回查仍 NotFound (例如对方 Create 后立即软删) → 向上抛 Conflict, 客户端重试。
	s.logger.Warn(ctx, "chat conversation create lost race; retrying FindActiveSingle",
		"tenant_id", tenantID, "account_id", accountID, "agent_id", ag.ID)
	winner, lookupErr := s.convs.FindActiveSingle(ctx, tenantID, accountID, ag.ID)
	if lookupErr == nil {
		return winner, nil
	}
	return nil, apperr.ErrConflict.Withf("conversation create lost race and FindActiveSingle still empty: %v", lookupErr)
}

// isUniqueViolation 判断 err 是否是 Postgres 23505 unique violation 且击中
// idx_conv_single_active_v2d (T2D.9 索引)。
//
// 用 ConstraintName 做精确匹配, 避免把别的 unique 冲突 (如 conversations.uuid 撞库)
// 也当成"复用机会"误吃掉真实错误。
func isUniqueViolation(err error) bool {
	if err == nil {
		return false
	}
	var pg *pgconn.PgError
	if !errors.As(err, &pg) {
		return false
	}
	if pg.Code != "23505" {
		return false
	}
	return pg.ConstraintName == "idx_conv_single_active_v2d"
}

// runAgent 走 OpenClaw Gateway v3 WS。Batch 2D T2D.1 起这是 chat 的唯一 runtime 路径,
// 不再经 runtime.Manager 调用旧 OpenResponses HTTP+SSE adapter (DEPRECATED, 详见
// `internal/adapter/runtime/openclaw/adapter.go` 文件头)。
//
// verParams 由 Send 同步加载 (T2D.3-B), 已校验 model 存在; runAgent 只负责传递。
//
// agentMsgUUID + conversationUUID 用于 T2D.5 SSE 事件路由 (block.delta / completed / failed
// 都带 message_uuid + conversation_uuid).
//
// Batch 3A T3.1: 不再持 *publisher, 改用 s.fanout.Publish; accountID/tenantID 自调用链上
// 一路传到 emitDelta / finalize, RedisFanout 据此投到 account:<id>:events.
func (s *impl) runAgentGoroutine(
	ctx context.Context,
	streamID string,
	accountID, runtimeAccountID, tenantID int64,
	ep gatewayws.Endpoint,
	ag *domagent.DigitalEmployee,
	promptText string,
	conversationUUID string,
	roomUUID string,
	agentMsgUUID string,
	verParams *versionParams,
	inputMessageUUID string,
) {
	defer s.fanout.Close(ctx, streamID)
	preparedPrompt := promptText
	ragQuery := s.chatRAGQueryText(ctx, promptText, inputMessageUUID, safeAgentName(ag))
	kc := s.prepareRuntimeKnowledgeContext(ctx, ChatRAGRequest{
		TenantID:         tenantID,
		AccountID:        accountID,
		Agent:            ag,
		Conversation:     &domconv.Conversation{UUID: conversationUUID},
		RoomUUID:         roomUUID,
		MessageUUID:      agentMsgUUID,
		QueryOriginal:    ragQuery,
		QueryRewritten:   ragQuery,
		InvocationSource: "pre_retrieve",
	})
	if s.openclawInputs != nil && strings.TrimSpace(inputMessageUUID) != "" {
		inputs, err := s.openclawInputs.PrepareOpenClawInputs(ctx, tenantID, accountID, ag, conversationUUID, inputMessageUUID)
		if err != nil {
			s.logger.Error(ctx, "chat openclaw input prepare failed",
				"agent", ag.UUID, "stream_id", streamID, "conversation_uuid", conversationUUID,
				"input_message_uuid", inputMessageUUID, "err", err)
			s.finalize(ctx, streamID, accountID, tenantID, conversationUUID, roomUUID, agentMsgUUID,
				nil, "failed", ErrCodeOpenClawInputPrepareFailed, "openclaw input prepare failed", nil)
			return
		}
		preparedPrompt = promptTextWithOpenClawInputs(promptText, inputs)
	}
	preparedPrompt = promptTextWithKnowledgeContext(preparedPrompt, kc)
	s.logger.Info(ctx, "chat openclaw v3 stream open",
		"agent", ag.UUID, "stream_id", streamID, "endpoint", ep.HTTPURL,
		"agent_version", verParams.Version, "model", verParams.Model,
		"room_uuid", roomUUID, "node_id", s.nodeID)
	s.runOpenClawV3(ctx, streamID, accountID, runtimeAccountID, tenantID, ep, ag, conversationUUID, roomUUID, agentMsgUUID, preparedPrompt, verParams, kc)
}

// awaitFinalize ADR-0028 §4.2 — HITL 暂停收尾。ZAP runtime 发 message.awaiting_user
// SSE 事件后, ZAP adapter 路由到此; 与 finalize 同生命周期点位但终态不一样:
//
//   - messages.status = 'awaiting_user' (业务态; 见 migration 000039 扩展 CHECK)
//   - messages.final  = true (流终态写入完毕; 后续 ZAP 输出由 /chat/respond 起的新 stream/新 message 承接)
//   - 写当前已收到的 blocks (HITL pause 时通常含 approval/form/action typed block)
//   - SSE 发 EventMessageAwaitingUser, 客户端把气泡切到 awaiting_user 视图
//   - message_streams.state 标 'done' (与 finalize 终态 done 同款; awaiting_user 是 messages
//     业务态, **不**翻 message_streams.state='awaiting'; ADR §4.2 设计纪律)
//   - fanout.Close + 释放 active stream 资源
//
// 不发 message.completed / .failed / .cancelled (否则客户端会看到矛盾终态)。
//
// 与 finalize 的关系: awaitFinalize 是 finalize 的兄弟方法, 共享相同的 stream 收尾资源释放;
// 调用方按 ZAP SSE 事件分流, 二者只调一个。awaitFinalize 不消费 errCode/errMsg, 因为
// awaiting_user 不是 error 路径。
func (s *impl) awaitFinalize(
	ctx context.Context,
	streamID string,
	accountID, tenantID int64,
	convoUUID, roomUUID, msgUUID string,
	blocks []map[string]any,
	awaitingBlockID string,
) {
	// F24: HITL pause is a terminal snapshot for this run (respond opens a new
	// stream + message = a new run; the awaiting run is settled by
	// CloseAwaitingRun when the user responds).
	if rec := s.runRecs.lookupStream(streamID); rec != nil {
		rec.Flush("awaiting_user", "", "", time.Now())
	}

	if blocks == nil {
		blocks = []map[string]any{}
	}

	// EMP block 校验 + fallback (与 finalize 同款; awaiting_user 也是 final 终态)。
	if s.empValidator != nil && len(blocks) > 0 {
		rewritten, fbs := s.empValidator.ValidateBlocks(ctx, blocks, "")
		if len(fbs) > 0 {
			blocks = rewritten
			s.publishEMPFallbackAudit(ctx, streamID, tenantID, msgUUID, fbs)
		}
	}

	// **顺序**: 必须**先**写 messages.status='awaiting_user', **后**翻 message_streams.state='done'。
	// 原因: streamStore.UpdateTerminalStateByStreamID 内部 SQL 是 `UPDATE ... WHERE state='active'`,
	// 即"active-only 转换"。如果先把 state 翻成 'done', 接着 messages.UpdateStream 失败需要走
	// finalize(failed) 兜底, 但 finalize 里同样调 UpdateTerminalStateByStreamID('failed') 也是
	// active-only — 此时 stream 已 'done', UPDATE 命中 0 行, state 保持 'done', 与
	// messages.status='failed' 不一致 (运维角度: stream 看似正常完成, 但 message 是 failed)。
	// 正确顺序: 先写 messages (业务态权威), 成功再翻 stream done; 失败时 stream 仍 'active' →
	// finalize 调 UpdateTerminalStateByStreamID('failed') 真能命中 → state=failed。

	// messages.status='awaiting_user', final=true; 写当前 blocks; 不动 error_*。
	// metadata 写 awaiting_block_id (可选); 不覆盖已有 usage 等。
	var meta map[string]any
	if strings.TrimSpace(awaitingBlockID) != "" {
		meta = map[string]any{"awaiting_block_id": awaitingBlockID}
	}
	// **DB 守门**: messages.UpdateStream 失败 (典型: migration 000039 未跑 / DB 抖动 /
	// CHECK 拒) → **不能**继续 publish message.awaiting_user, 否则客户端看到 awaiting_user 但
	// DB 不是 awaiting_user, 后续 /chat/respond claim 不到 (业务卡死)。
	// 改走 finalize(failed) 路径 — finalize 内 UpdateTerminalStateByStreamID 会把 stream 翻成
	// 'failed' (此时 stream 仍 'active', active-only 守卫能命中); messages.UpdateStream 写
	// status='failed' (failed 状态 CHECK 一定允许, 不会再撞同样的约束)。client 看到 failed,
	// 不会卡死等回应; 运维侧 messages.status 与 message_streams.state 同步一致。
	if uerr := s.messages.UpdateStream(context.Background(), streamID, blocks, "awaiting_user", true, "", "", meta); uerr != nil {
		s.logger.Error(ctx, "chat awaitFinalize: messages.UpdateStream awaiting_user failed; falling back to failed terminal",
			"stream_id", streamID, "msg_uuid", msgUUID)
		// activeStreams 仍要清 (与 finalize 同款; cancel ctx 不留)。
		if s.activeStreams != nil {
			s.activeStreams.remove(streamID)
		}
		// stream 仍 'active' → finalize 内 UpdateTerminalStateByStreamID('failed') 真能翻成 failed。
		// 错误文案用固定 sanitized 防止泄露 DB 原始错。
		s.finalize(ctx, streamID, accountID, tenantID, convoUUID, roomUUID, msgUUID,
			nil, "failed", ErrCodeProtocolUnsupported, sanitizedRuntimeFailureMessage, nil)
		return
	}

	// messages 写入成功 → 翻 message_streams.state='done' (本轮 stream 不再产事件)。
	// 失败仅 Warn — messages 已是 awaiting_user 权威态, stream 状态滞后属可观测但不卡业务。
	if s.streamStore != nil {
		if _, _, err := s.streamStore.UpdateTerminalStateByStreamID(context.Background(), streamID, "done"); err != nil {
			s.logger.Warn(ctx, "chat awaitFinalize: update terminal state failed",
				"stream_id", streamID, "err", err)
		}
	}

	// activeStreams 释放 (与 finalize 同款)。
	if s.activeStreams != nil {
		s.activeStreams.remove(streamID)
	}

	// SSE: message.awaiting_user。Final=true 让 transport SSE handler 在 publish 后断开连接
	// (与 finalize 终态同款; 客户端订阅新 stream 由 /chat/respond 返回的 new stream_id 重连)。
	// **只有** messages.status='awaiting_user' 成功落库后才发布; 否则上方 fallback 已 return。
	ev := StreamEvent{
		Kind:             EventMessageAwaitingUser,
		ConversationUUID: convoUUID,
		RoomUUID:         roomUUID,
		MessageUUID:      msgUUID,
		Blocks:           blocks,
		Final:            true,
		Timestamp:        time.Now(),
	}
	if err := s.fanout.Publish(ctx, streamID, accountID, tenantID, ev); err != nil {
		s.logger.Warn(ctx, "chat fanout publish awaiting_user failed", "stream_id", streamID, "err", err)
	}
}

// finalize 终态写入 + 发送 SSE 终态事件 (Batch 2D T2D.4 + T2D.5; T2E.6 加 RoomUUID;
// Batch 3A T3.1 把 publish 走 fanout; Batch 3B T3.5 把 message_streams.state 收尾;
// Batch 3B 返修 final patch 加 currentState gate, 见下).
//
// 3B 返修 final patch (currentState gate):
//
//	先调 streamStore.UpdateTerminalStateByStreamID 拿 (changed, currentState):
//	  a. currentState=='cancelled' 且 status != 'cancelled' → suppressed=true
//	     典型: cross-node optimisticCancel 已经把 state 翻 'cancelled' 并 publish
//	     message.cancelled; owner 节点的 goroutine 没收到 cancel 信号自然完成, 想 finalize
//	     'final'/'failed'. 这条路径下我们必须:
//	       - 把 messages.status 写成 'cancelled' (保持 messages 与 message_streams 一致,
//	         不能让 messages.status 留 streaming, 也不能把它从 cancelled 反写成 final).
//	       - **跳过 publish** — 客户端已经收到 message.cancelled, 再发 message.completed
//	         会让 UI 终态矛盾.
//	       - usage 仍然落库用于计费; stop 后迟到的 blocks 丢弃, 防止客户端重启后
//	         从历史恢复已经取消的完整回答.
//	  b. 其它情况按正常路径: messages.UpdateStream(status) + publish 对应终态事件.
func (s *impl) finalize(
	ctx context.Context,
	streamID string,
	accountID, tenantID int64,
	convoUUID, roomUUID, msgUUID string,
	blocks []map[string]any,
	status string,
	errCode, errMsg string,
	usage map[string]any,
	extraMetadata ...map[string]any,
) {
	// F24: flush the run recorder first (pure memory + async write; must see
	// the final usage even on suppressed/cancelled paths).
	if rec := s.runRecs.lookupStream(streamID); rec != nil {
		rec.OnUsage(usage)
		rec.Flush(status, errCode, errMsg, time.Now())
	}

	if blocks == nil {
		blocks = []map[string]any{}
	}
	var meta map[string]any
	if len(usage) > 0 {
		meta = map[string]any{"usage": usage}
	} else {
		meta = map[string]any{"usage": map[string]any{}}
	}
	for _, extra := range extraMetadata {
		for k, v := range extra {
			if k == "" {
				continue
			}
			meta[k] = v
		}
	}

	// 3D T3.10: EMP block 校验 + fallback. clientVer="" → 跳过 version 检查 (server-side
	// finalize 拿不到客户端版本, 只过滤 unknown/draft/deprecated).
	if s.empValidator != nil && len(blocks) > 0 {
		rewritten, fbs := s.empValidator.ValidateBlocks(ctx, blocks, "")
		if len(fbs) > 0 {
			blocks = rewritten
			s.publishEMPFallbackAudit(ctx, streamID, tenantID, msgUUID, fbs)
		}
	}

	// status → message_streams.state 映射.
	msState := "done"
	switch status {
	case "failed":
		msState = "failed"
	case "cancelled":
		msState = "cancelled"
	}

	// 3B 返修 final patch: 通过 UpdateTerminalStateByStreamID 拿到 currentState,
	// 据此 gate 后续 messages.UpdateStream + publish.
	suppressed := false
	if s.streamStore != nil {
		_, currentState, err := s.streamStore.UpdateTerminalStateByStreamID(context.Background(), streamID, msState)
		if err != nil {
			s.logger.Warn(ctx, "chat finalize: update terminal state failed",
				"stream_id", streamID, "ms_state", msState, "err", err)
			// DB 抖动: 仍按原行为继续写 messages + publish (best-effort, 不丢终态).
		}
		if currentState == "cancelled" && status != "cancelled" {
			s.logger.Info(ctx, "chat finalize: stream already cancelled by stop; suppressing terminal publish",
				"stream_id", streamID, "wanted_status", status, "current_state", currentState)
			suppressed = true
		}
	}

	if suppressed {
		// 把 messages.status 同步成 cancelled, 保持 messages.status 与 message_streams.state 一致;
		// stop 后才到达的 blocks 必须丢弃, 否则客户端重启加载历史时会复活已取消回复;
		// usage 仍通过 metadata 保留用于计费与审计.
		_ = s.messages.UpdateStream(context.Background(), streamID, []map[string]any{}, "cancelled", true, "", "", meta)
	} else {
		_ = s.messages.UpdateStream(context.Background(), streamID, blocks, status, true, errCode, errMsg, meta)
	}

	// "final" = ZAP 路径收尾状态 (zap/dsh); 之前漏掉导致 ZAP 员工 token 用量不进 usage/summary 统计。
	// 在开 goroutine 之前取重试次数：recorder 可能在 flush 后被注销。
	retryIndex := s.runRecs.lookupStream(streamID).RetryIndex()
	if s.llmBiller != nil && len(usage) > 0 && (status == "completed" || status == "final" || status == "") {
		go func() {
			model, _ := usage["model"].(string)
			input := toInt64(usage, "input_tokens")
			output := toInt64(usage, "output_tokens")
			if input > 0 || output > 0 {
				// record-only: 资金扣费走 AIGC usage push, 这里不扣积分.
				if err := s.llmBiller.RecordProvisionalLLMUsage(context.Background(), tenantID, accountID, streamID, model, input, output, retryIndex); err != nil {
					s.logger.Warn(ctx, "llm usage record failed", "stream_id", streamID, "err", err)
				}
			}
		}()
	}

	// 从 in-process activeStreams 删 entry (无论是否成功; 终态后无人再 cancel 它).
	if s.activeStreams != nil {
		s.activeStreams.remove(streamID)
	}

	if suppressed {
		// stop 路径已经 publish 过 message.cancelled, 这里不再发任何 SSE.
		return
	}

	ev := StreamEvent{
		ConversationUUID: convoUUID,
		RoomUUID:         roomUUID,
		MessageUUID:      msgUUID,
		Final:            true,
		Timestamp:        time.Now(),
	}
	switch status {
	case "failed":
		ev.Kind = EventMessageFailed
		ev.ErrorCode = errCode
		ev.ErrorMessage = errMsg
		ev.Blocks = blocks
	case "cancelled":
		ev.Kind = EventMessageCancelled
		// Preserve validated local partial files without changing ordinary cloud stop payloads.
		for _, block := range blocks {
			if block["local_artifact"] != nil {
				ev.Blocks = blocks
				break
			}
		}
	default:
		ev.Kind = EventMessageCompleted
		ev.Blocks = blocks
		if u, ok := meta["usage"].(map[string]any); ok {
			ev.Usage = u
		}
	}
	if err := s.fanout.Publish(ctx, streamID, accountID, tenantID, ev); err != nil {
		s.logger.Warn(ctx, "chat fanout publish final failed", "stream_id", streamID, "err", err)
	}
}

func toInt64(m map[string]any, key string) int64 {
	v, ok := m[key]
	if !ok {
		return 0
	}
	switch n := v.(type) {
	case float64:
		return int64(n)
	case int64:
		return n
	case int:
		return int64(n)
	default:
		return 0
	}
}

// SubscribeWithOwner 订阅前校验 (accountID, tenantID) 是否为 streamID 的注册者。
//
// Batch1 返修 #5：admin try-chat stream / 后续 M4 账号级 SSE 都用它做归属校验，
// 避免任何持有 streamID 的旁观者订阅他人的流。
//
// Batch 3A T3.1: 走 fanout.Owner 查归属 (LocalFanout 用 in-process 表, RedisFanout 用 HASH).
func (s *impl) SubscribeWithOwner(ctx context.Context, accountID, tenantID int64, streamID string) (<-chan StreamEvent, func(), error) {
	ownerAcc, ownerTen, ok, err := s.fanout.Owner(ctx, streamID)
	if err != nil {
		return nil, nil, apperr.ErrInternal.Wrap(err)
	}
	if !ok {
		return nil, nil, apperr.ErrNotFound.Withf("stream not found")
	}
	if ownerAcc != 0 && (ownerAcc != accountID || ownerTen != tenantID) {
		return nil, nil, apperr.ErrForbidden.Withf("stream not owned by current account")
	}
	return s.Subscribe(ctx, streamID)
}

func (s *impl) Subscribe(ctx context.Context, streamID string) (<-chan StreamEvent, func(), error) {
	ch, cancel, err := s.fanout.Subscribe(ctx, streamID)
	if err != nil {
		// 把 fanout 的"找不到"错误统一为 apperr.ErrNotFound, 保持 transport 层 404 行为不变.
		if strings.Contains(err.Error(), "stream not found") {
			return nil, nil, apperr.ErrNotFound.Withf("stream not found")
		}
		return nil, nil, apperr.ErrInternal.Wrap(err)
	}
	return ch, cancel, nil
}

// SubscribeAccount Batch 3A T3.2 + 3A 返修 #1: 账号级 SSE 入口, 走 tenant + account 双重分区.
//
// tenantID **必须**传; 通道命名 tenant:<t>:account:<a>:events 让同一 account 跨租户也
// 不会串台. lastEventID 见 fanout 注释.
func (s *impl) SubscribeAccount(ctx context.Context, accountID, tenantID int64, lastEventID string) (<-chan AccountEvent, func(), bool, error) {
	if accountID == 0 {
		return nil, nil, false, apperr.ErrUnauthorized.Withf("account required")
	}
	if tenantID == 0 {
		return nil, nil, false, apperr.ErrForbidden.Withf("tenant scope required")
	}
	ch, cancel, gap, err := s.fanout.SubscribeAccount(ctx, accountID, tenantID, lastEventID)
	if err != nil {
		return nil, nil, false, apperr.ErrInternal.Wrap(err)
	}
	return ch, cancel, gap, nil
}

