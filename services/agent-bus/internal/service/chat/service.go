// SendReq 客户端发消息请求。
//
// Batch 3C T3.8: 新增 FileUUIDs (DTO 字段名 `file_uuids`), 接收已经 presign+confirm 的
// staged 附件 UUID 列表; Send 在 user message 落库后原子地把它们绑成 bound:
// 失败 → ErrAttachmentNotOwned + 整事务回滚 (user message / agent message 都不留).
type SendReq struct {
	AgentUUID        string           `json:"agent_uuid"`
	ConversationUUID string           `json:"conversation_uuid,omitempty"`
	Text             string           `json:"text"`
	Blocks           []map[string]any `json:"blocks,omitempty"`
	ModelHint        string           `json:"model_hint,omitempty"`
	LocalDeviceUUID  string           `json:"local_device_id,omitempty"`
	LocalContextID   string           `json:"local_context_id,omitempty"`
	// Transport identity, never decoded from a client-controlled body.
	LocalLoginSessionUUID string `json:"-"`
	// FileUUIDs 已 staged 的附件 UUID; service 内调 attachmentBinder.BindToMessage 绑定。
	// DTO 字段名为 file_uuids (与 docs/modules/m4 §4.3 / boundaries §6.5 一致); SQL 仍按
	// message_files.uuid 列做 UPDATE.
	FileUUIDs []string `json:"file_uuids,omitempty"`
	// M6 Phase A: 用户选中的 Composer Skill UUID + 该 skill 的 chip 参数.
	// 校验 (chat.Send / room.SendMessage 同款):
	//   1. agent 必须装配此 skill (binding 命中); 否则 chat.skill_not_attached
	//   2. composer_params 序列化字节 ≤ composer.ComposerParamsMaxBytes (16KB); 否则
	//      chat.composer_params_too_large
	// 通过 → user message metadata 落 composer_skill_uuid / composer_skill_code /
	// composer_params 原样, 让 Agent 自己消费. Bus 不解释 chip 字段.
	ComposerSkillUUID string         `json:"composer_skill_uuid,omitempty"`
	ComposerParams    map[string]any `json:"composer_params,omitempty"`

	// F03 v0.9.1 §3.4 / §4.4 — 客户端选中 chip 后随消息透传给 Agent 的字段。
	// Bus **不解析** skill_params 内字段含义；仅做：
	//   1. skill_params JSON 序列化大小 ≤ AGBUS_SKILL_PARAMS_MAX_BYTES（16KB）
	//   2. metadata 透传给 Agent runtime（Agent 自行加载 SKILL.md 解析）
	// rail-membership 校验由 F09 chat hook 接管（spec §4.4 完整链路 v0.9.2+）。
	ActiveSkillUUID       string         `json:"active_skill_uuid,omitempty"`
	ActiveSkillKind       string         `json:"active_skill_kind,omitempty"`
	ActiveSkillBuiltinKey string         `json:"active_skill_builtin_key,omitempty"`
	ActiveSkillCode       string         `json:"active_skill_code,omitempty"`
	ActiveSkillVersion    string         `json:"active_skill_version,omitempty"`
	SkillParams           map[string]any `json:"skill_params,omitempty"`
}

