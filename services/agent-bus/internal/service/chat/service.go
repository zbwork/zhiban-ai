func firstLine(s string) string {
	if s == "" {
		return ""
	}
	if i := strings.IndexByte(s, '\n'); i > 0 {
		s = s[:i]
	}
	if len([]rune(s)) > 40 {
		runes := []rune(s)
		return string(runes[:40]) + "…"
	}
	return s
}

