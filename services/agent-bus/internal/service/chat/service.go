// AvatarURLResolver 把持久化的头像引用 (oss://key / 静态路径 / 历史 URL) 解析成
// 客户端可加载的 URL。从 cmd/bus 注入, chat service 不感知对象存储签名细节。
type AvatarURLResolver func(ctx context.Context, tenantID int64, raw string) string

// SetAvatarURLResolverOnService 为会话列表 DTO 注入可选头像解析;
// 非默认实现 (测试 fake) 上是 no-op。
func SetAvatarURLResolverOnService(svc Service, resolver AvatarURLResolver) {
	if im, ok := svc.(*impl); ok {
		im.avatarURLResolver = resolver
	}
}

func (s *impl) ListConversations(ctx context.Context, accountID, tenantID int64, limit, offset int, includeHidden bool) ([]domconv.ListItem, int64, error) {
	// Batch 2E T2E.7B: 单聊 + active 群 conversations 混排; LEFT JOIN rooms 拿 room 元数据。
	// Round-7 P2-2: hidden 过滤 + CAS 字段下推到 repo SQL, 不再在 transport 层 in-memory merge.
	items, total, err := s.convs.ListForAccount(ctx, tenantID, accountID, limit, offset, includeHidden)
	if err != nil {
		return nil, 0, err
	}
	if shouldSeedSupportWelcomeConversation(items, total, offset, includeHidden) {
		seeded, seedErr := s.seedSupportWelcomeIfFirstVisibleList(ctx, accountID, tenantID)
		if seedErr != nil {
			if s.logger != nil {
				s.logger.Warn(ctx, "support welcome: seed failed",
					"tenant_id", tenantID, "account_id", accountID, "err", seedErr.Error())
			}
		} else if seeded {
			items, total, err = s.convs.ListForAccount(ctx, tenantID, accountID, limit, offset, includeHidden)
			if err != nil {
				return nil, 0, err
			}
		}
	}
	// 头像引用解析: 自定义上传的数字员工头像存的是 oss://agent-avatars/<key>
	// (digital_employees.avatar_url), 通讯录/数字员工接口已走 ResolveURL 现签,
	// 会话列表此前漏掉 → 客户端拿到字面量 oss:// 渲染失败 (内置头像是
	// /api/assets 路径不受影响)。同列表内相同引用只签一次。
	var avatarMemo map[string]string
	resolveAvatar := func(raw string) string {
		raw = strings.TrimSpace(raw)
		if raw == "" || s.avatarURLResolver == nil {
			return raw
		}
		if v, ok := avatarMemo[raw]; ok {
			return v
		}
		v := strings.TrimSpace(s.avatarURLResolver(ctx, tenantID, raw))
		if v == "" {
			v = raw
		}
		if avatarMemo == nil {
			avatarMemo = map[string]string{}
		}
		avatarMemo[raw] = v
		return v
	}
	// 把 kind / room_uuid / room_kind 继续塞进 Metadata 以兼容老前端 (Conversation 嵌入字段直读);
	// 同时返回 ListItem, transport 直接消费 Hidden / LastReadMessageUUID / UnreadSnapshot.
	for i := range items {
		it := &items[i]
		if it.Metadata == nil {
			it.Metadata = map[string]any{}
		}
		it.Metadata["kind"] = it.Kind
		if it.RoomUUID != "" {
			it.Metadata["room_uuid"] = it.RoomUUID
		}
		if it.RoomKind != "" {
			it.Metadata["room_kind"] = it.RoomKind
		}
		it.Avatar = resolveAvatar(it.Avatar)
		it.AgentAvatar = resolveAvatar(it.AgentAvatar)
		for p := range it.Participants {
			it.Participants[p].Avatar = resolveAvatar(it.Participants[p].Avatar)
		}
	}
	return items, total, nil
}

func (s *impl) History(ctx context.Context, accountID, tenantID int64, convoUUID string, limit int) ([]dommsg.Message, error) {
	c, err := s.convs.GetByUUID(ctx, convoUUID)
	if err != nil {
		return nil, err
	}
	if c.AccountID != accountID || c.TenantID != tenantID {
		return nil, apperr.ErrForbidden
	}
	var after *time.Time
	if s.convState != nil {
		clearedAt, err := s.convState.ClearedAt(ctx, accountID, tenantID, convoUUID)
		if err != nil {
			return nil, apperr.ErrInternal.Wrap(err)
		}
		after = clearedAt
	}
	return s.messages.History(ctx, dommsg.HistoryFilter{ConversationID: c.ID, Limit: limit, After: after})
}

