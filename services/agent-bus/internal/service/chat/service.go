func classifyRunStartFailure(cause error) runStartFailure {
	if appErr, ok := apperr.AsError(cause); ok && appErr.Message == ErrCodeRuntimeWarming ||
		strings.Contains(cause.Error(), ErrCodeRuntimeWarming) {
		return runStartFailure{
			code:       ErrCodeRuntimeWarming,
			text:       "数字员工正在准备中，请稍后重试。",
			diagnostic: cause.Error(),
		}
	}
	return runStartFailure{
		code:       ErrCodeRuntimeUpstreamFailure,
		text:       "数字员工暂时无法回复，请稍后再试。",
		diagnostic: cause.Error(),
	}
}

// useQueue doc-12 Task D: 是否走 DB 队列异步消费。
// 普通聊天需要 queue flag；ForceQueue 可绕过该 flag。两者都必须装齐 chatTasks 且有 user 消息 uuid。
func (s *impl) useQueue(in runAgentInternalIn) bool {
	if in.Agent != nil && in.Agent.ExecutionLocus == "local" {
		return false
	}
	if in.OrchestratorStrategy != "" {
		return false
	}
	if in.Framework == FrameworkSupportBuiltin {
		return false
	}
	return (s.queueEnabled || in.ForceQueue) && s.chatTasks != nil && in.UserMessageUUID != ""
}

// runtimeAccountIDForAgent separates the caller from the per-user runtime owner.
// A private digital employee exists only in its creator's runtime; group authorization
// lets other members invoke it but never installs or executes it in the caller's instance.
func runtimeAccountIDForAgent(callerAccountID int64, ag *domagent.DigitalEmployee) (int64, error) {
	if callerAccountID <= 0 || ag == nil {
		return 0, apperr.ErrInvalidParams.Withf("chat runtime owner: caller/agent required")
	}
	if strings.EqualFold(strings.TrimSpace(ag.Visibility), "private") {
		if ag.CreatorID <= 0 {
			return 0, apperr.ErrInternal.Withf("chat runtime owner: private agent missing creator")
		}
		return ag.CreatorID, nil
	}
	return callerAccountID, nil
}

func promptTextWithSkillSlugs(prompt string, slugs []string) string {
	clean := make([]string, 0, len(slugs))
	seen := make(map[string]struct{}, len(slugs))
	for _, raw := range slugs {
		slug := strings.TrimSpace(raw)
		if slug == "" {
			continue
		}
		if _, ok := seen[slug]; ok {
			continue
		}
		seen[slug] = struct{}{}
		clean = append(clean, slug)
	}
	if len(clean) == 0 {
		return prompt
	}
	instruction := "【技能指令】本轮请调用以下已安装技能来完成任务（按顺序优先尝试）：" +
		strings.Join(clean, "、") +
		"。每个技能位于工作目录 skills/<slug> 下，请读取其 SKILL.md 并按说明使用。"
	body := strings.TrimSpace(prompt)
	if body == "" {
		return instruction
	}
	return instruction + "\n\n" + prompt
}

// skillSlugsFromBlocks 从持久化 user message 的结构化 skill block 恢复本轮技能。
// WuKong 直发、/chat/send 降级和队列 worker 都必须以 blocks 为同一事实源，避免
// transport 切换后技能静默丢失。name 只用于客户端展示，运行时只消费 slug。
func skillSlugsFromBlocks(blocks []map[string]any) []string {
	seen := make(map[string]struct{})
	out := make([]string, 0)
	for _, block := range blocks {
		typeName, _ := block["type"].(string)
		if strings.ToLower(strings.TrimSpace(typeName)) != "skill" {
			continue
		}
		raw := block["slug"]
		if raw == nil {
			raw = block["skill_slug"]
		}
		slugValue, _ := raw.(string)
		slug := strings.TrimSpace(slugValue)
		if slug == "" {
			continue
		}
		if _, ok := seen[slug]; ok {
			continue
		}
		seen[slug] = struct{}{}
		out = append(out, slug)
	}
	return out
}

